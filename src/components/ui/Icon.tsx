export type IconName = keyof typeof icons;

export function Icon({
  name,
  className,
  strokeWidth = 1.75,
}: {
  name: string;
  className?: string;
  strokeWidth?: number;
}) {
  const Cmp = icons[name as IconName] ?? Ship;
  return <Cmp className={className} strokeWidth={strokeWidth} aria-hidden />;
}
